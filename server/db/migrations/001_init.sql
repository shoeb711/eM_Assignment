-- =====================================================================
-- 001_init.sql  -  Project Portfolio & Financial Control Portal schema
-- =====================================================================
-- Groups (Section 3.3 of the assignment):
--   People / portfolio : departments, users, projects, project_members
--   Delivery           : tasks, milestones, risks, progress_snapshots
--   Governance         : change_requests, change_request_history, audit_events
--   Finance            : cost_categories, budget_revisions, cost_transactions, financial_forecasts
--   Automation         : automation_runs, notifications
--
-- Conventions
--   * id columns are auto-numbered (GENERATED BY DEFAULT AS IDENTITY)
--   * money = NUMERIC(14,2)  (exact decimals, never floating point)
--   * "version" columns support optimistic locking (detect two people editing the same row)
--   * fixed lists of values (status, role, ...) are enforced with CHECK constraints
-- =====================================================================


-- ---------------------------------------------------------------------
-- PEOPLE / PORTFOLIO
-- ---------------------------------------------------------------------

CREATE TABLE departments (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id INT NOT NULL REFERENCES departments(id),
  full_name     TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('CONTRIBUTOR', 'PROJECT_MANAGER', 'ADMIN')),
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE projects (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           TEXT NOT NULL UNIQUE,                        -- e.g. PRJ-001
  name           TEXT NOT NULL,
  description    TEXT,
  department_id  INT NOT NULL REFERENCES departments(id),
  owner_id       INT NOT NULL REFERENCES users(id),           -- the project manager
  status         TEXT NOT NULL CHECK (status IN ('PLANNING', 'ACTIVE', 'ON_HOLD', 'COMPLETED', 'CANCELLED')),
  start_date     DATE NOT NULL,
  end_date       DATE NOT NULL,
  initial_budget NUMERIC(14,2) NOT NULL CHECK (initial_budget >= 0),
  version        INT NOT NULL DEFAULT 1,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date)
);
CREATE INDEX idx_projects_department ON projects(department_id);
CREATE INDEX idx_projects_owner      ON projects(owner_id);
CREATE INDEX idx_projects_status     ON projects(status);

-- Who works on which project (many-to-many). Used for "scoped access":
-- a user may only see projects they own or are a member of (admins see all).
CREATE TABLE project_members (
  project_id INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id    INT NOT NULL REFERENCES users(id),
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX idx_project_members_user ON project_members(user_id);


-- ---------------------------------------------------------------------
-- DELIVERY
-- ---------------------------------------------------------------------

CREATE TABLE tasks (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  description  TEXT,
  assignee_id  INT REFERENCES users(id),                       -- NULL = unassigned
  status       TEXT NOT NULL CHECK (status IN ('TODO', 'IN_PROGRESS', 'BLOCKED', 'DONE')),
  priority     TEXT NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  start_date   DATE,
  due_date     DATE NOT NULL,
  weight       INT NOT NULL DEFAULT 1 CHECK (weight BETWEEN 1 AND 10),   -- importance in project progress
  progress     INT NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  completed_at DATE,
  version      INT NOT NULL DEFAULT 1,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- a DONE task must be 100% and have a completion date
  CHECK (status <> 'DONE' OR (progress = 100 AND completed_at IS NOT NULL))
);
CREATE INDEX idx_tasks_project  ON tasks(project_id, status);
CREATE INDEX idx_tasks_assignee ON tasks(assignee_id);
CREATE INDEX idx_tasks_due      ON tasks(due_date);

CREATE TABLE milestones (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  due_date     DATE NOT NULL,
  status       TEXT NOT NULL CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'ACHIEVED', 'MISSED')),
  completed_at DATE,
  version      INT NOT NULL DEFAULT 1,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_milestones_project ON milestones(project_id, due_date);

CREATE TABLE risks (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  type        TEXT NOT NULL CHECK (type IN ('RISK', 'ISSUE')),
  title       TEXT NOT NULL,
  description TEXT,
  owner_id    INT REFERENCES users(id),
  probability INT NOT NULL CHECK (probability BETWEEN 1 AND 5),
  impact      INT NOT NULL CHECK (impact BETWEEN 1 AND 5),
  score       INT GENERATED ALWAYS AS (probability * impact) STORED,   -- calculated by the database
  mitigation  TEXT,
  due_date    DATE,
  status      TEXT NOT NULL CHECK (status IN ('OPEN', 'MITIGATING', 'CLOSED')),
  version     INT NOT NULL DEFAULT 1,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_risks_project ON risks(project_id, status);

-- Historical progress (one row per project per month) for trend charts.
CREATE TABLE progress_snapshots (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id    INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  snapshot_date DATE NOT NULL,
  progress_pct  NUMERIC(5,2) NOT NULL CHECK (progress_pct BETWEEN 0 AND 100),
  actual_spend  NUMERIC(14,2) NOT NULL CHECK (actual_spend >= 0),
  UNIQUE (project_id, snapshot_date)
);


-- ---------------------------------------------------------------------
-- GOVERNANCE
-- ---------------------------------------------------------------------

CREATE TABLE change_requests (
  id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id           INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title                TEXT NOT NULL,
  description          TEXT NOT NULL,
  cost_impact          NUMERIC(14,2) NOT NULL DEFAULT 0,
  schedule_impact_days INT NOT NULL DEFAULT 0,
  status               TEXT NOT NULL CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED', 'RETURNED')),
  submitted_by         INT NOT NULL REFERENCES users(id),
  submitted_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_by           INT REFERENCES users(id),
  decided_at           TIMESTAMPTZ,
  decision_reason      TEXT,
  version              INT NOT NULL DEFAULT 1,
  -- Self-approval prevention, enforced by the database itself (not only by the API)
  CONSTRAINT chk_no_self_decision CHECK (decided_by IS NULL OR decided_by <> submitted_by)
);
CREATE INDEX idx_change_requests_project ON change_requests(project_id, status);

-- Every status change of a change request (who, when, from -> to, why). Append-only.
CREATE TABLE change_request_history (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_request_id INT NOT NULL REFERENCES change_requests(id) ON DELETE CASCADE,
  from_status       TEXT,                    -- NULL for the first "submitted" entry
  to_status         TEXT NOT NULL,
  actor_id          INT NOT NULL REFERENCES users(id),
  comment           TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_cr_history_cr ON change_request_history(change_request_id);

-- General activity log (logins, cost postings, budget decisions, ...). Append-only.
CREATE TABLE audit_events (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id    INT REFERENCES users(id),
  action      TEXT NOT NULL,                 -- e.g. COST_POSTED, LOGIN, BUDGET_REVISION_APPROVED
  entity_type TEXT NOT NULL,                 -- e.g. cost_transaction, project
  entity_id   INT,
  details     JSONB,
  request_id  TEXT,                          -- links the event to the API request log line
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_events(entity_type, entity_id);
CREATE INDEX idx_audit_created ON audit_events(created_at);


-- ---------------------------------------------------------------------
-- FINANCE
-- ---------------------------------------------------------------------

CREATE TABLE cost_categories (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

-- Changes to a project's approved budget. Only APPROVED revisions count
-- towards the "current approved budget".
CREATE TABLE budget_revisions (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id        INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  amount            NUMERIC(14,2) NOT NULL CHECK (amount <> 0),   -- positive = increase, negative = decrease
  reason            TEXT NOT NULL,
  status            TEXT NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  change_request_id INT REFERENCES change_requests(id),            -- optional explicit link to a change request
  requested_by      INT NOT NULL REFERENCES users(id),
  requested_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_by        INT REFERENCES users(id),
  decided_at        TIMESTAMPTZ,
  CONSTRAINT chk_no_self_budget_decision CHECK (decided_by IS NULL OR decided_by <> requested_by)
);
CREATE INDEX idx_budget_revisions_project ON budget_revisions(project_id, status);

CREATE TABLE cost_transactions (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id      INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  category_id     INT NOT NULL REFERENCES cost_categories(id),
  description     TEXT NOT NULL,
  amount          NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  txn_date        DATE NOT NULL,
  status          TEXT NOT NULL CHECK (status IN ('DRAFT', 'POSTED')),
  created_by      INT NOT NULL REFERENCES users(id),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  posted_by       INT REFERENCES users(id),
  posted_at       TIMESTAMPTZ,
  idempotency_key TEXT UNIQUE,              -- stops a double-click creating the same cost twice
  CHECK (status = 'DRAFT' OR (posted_by IS NOT NULL AND posted_at IS NOT NULL))
);
CREATE INDEX idx_costs_project_date ON cost_transactions(project_id, txn_date);
CREATE INDEX idx_costs_category     ON cost_transactions(category_id);

-- Planned future spend per project per month (used for forecast-to-complete and EAC).
CREATE TABLE financial_forecasts (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  month      DATE NOT NULL CHECK (EXTRACT(DAY FROM month) = 1),   -- always the 1st of the month
  amount     NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  created_by INT REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (project_id, month)
);


-- ---------------------------------------------------------------------
-- AUTOMATION / LOGGING
-- ---------------------------------------------------------------------

-- One row per execution of an automation job (success or failure).
CREATE TABLE automation_runs (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name        TEXT NOT NULL,
  status          TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
  started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at     TIMESTAMPTZ,
  items_processed INT NOT NULL DEFAULT 0,
  attempt         INT NOT NULL DEFAULT 1,
  error_message   TEXT
);

-- In-app notifications created by automations.
-- event_key is UNIQUE, so the same alert can never be created twice (duplicate protection).
CREATE TABLE notifications (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           INT NOT NULL REFERENCES users(id),
  project_id        INT REFERENCES projects(id) ON DELETE CASCADE,
  automation_run_id INT REFERENCES automation_runs(id),
  type              TEXT NOT NULL,           -- e.g. TASK_OVERDUE, BUDGET_OVERRUN
  title             TEXT NOT NULL,
  message           TEXT NOT NULL,
  event_key         TEXT NOT NULL UNIQUE,    -- e.g. TASK_OVERDUE:task:42:user:7
  is_read           BOOLEAN NOT NULL DEFAULT FALSE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user ON notifications(user_id, is_read);


-- ---------------------------------------------------------------------
-- DATABASE-LEVEL PROTECTION RULES (triggers)
-- ---------------------------------------------------------------------

-- 1) A POSTED cost can never be edited or deleted - not even by a buggy API call
--    or someone running SQL by hand. (Drafts can still be edited, and posting a
--    draft is allowed because the OLD row is still DRAFT at that moment.)
CREATE FUNCTION protect_posted_costs() RETURNS trigger AS $$
BEGIN
  IF OLD.status = 'POSTED' THEN
    RAISE EXCEPTION 'Posted cost transaction % cannot be changed or deleted', OLD.id;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_protect_posted_costs
  BEFORE UPDATE OR DELETE ON cost_transactions
  FOR EACH ROW EXECUTE FUNCTION protect_posted_costs();

-- 2) History / audit tables are append-only: rows can be added, never changed or removed.
CREATE FUNCTION block_history_changes() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is append-only: rows cannot be changed or deleted', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cr_history_append_only
  BEFORE UPDATE OR DELETE ON change_request_history
  FOR EACH ROW EXECUTE FUNCTION block_history_changes();

CREATE TRIGGER trg_audit_append_only
  BEFORE UPDATE OR DELETE ON audit_events
  FOR EACH ROW EXECUTE FUNCTION block_history_changes();
